def require(condition, message):
    if not condition:
        raise AssertionError(message)


def near(actual, expected, tolerance=1e-12):
    require(abs(actual - float(expected)) <= tolerance, (actual, str(expected)))


def rejected(call):
    try:
        call()
    except (ValueError, TypeError, KeyError):
        return
    raise AssertionError("invalid input unexpectedly accepted")


def load_module():
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location("v04_c12_benchmark_under_test", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class ChapterParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.worked = 0
        self.exercises = 0
        self.solutions = 0
        self.sources = set()
        self.links = []
        self.in_exercises = False
        self.in_solutions = False

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "aside" and attrs.get("class") == "worked":
            self.worked += 1
        if tag == "ol" and attrs.get("class") == "exercises":
            self.in_exercises = True
        if tag == "details" and attrs.get("class") == "solutions":
            self.in_solutions = True
        if tag == "li":
            self.exercises += self.in_exercises
            self.solutions += self.in_solutions
        if "data-source" in attrs:
            self.sources.add(attrs["data-source"])
        if tag == "a":
            self.links.append(attrs.get("href", ""))

    def handle_endtag(self, tag):
        if tag == "ol":
            self.in_exercises = False
        if tag == "details":
            self.in_solutions = False


def check():
    module = load_module()
    checks = []
    data, manifest = module.load_inputs(PROJECTS)
    report = module.calculate(data)
    rows = {(row["period"], row["adjustment"]): row for row in data["rows"]}
    require(set(rows) == set(REFERENCE), "frozen keys")
    for key, values in REFERENCE.items():
        row = rows[key]
        require(tuple(row[f] for f in FIELDS) + (row["published_rate_percent"],) == values,
                "official frozen value mismatch: " + str(key))
    checks.append("All six period/adjustment records and 36 source numeric fields match the separately recorded archived Table A-1 TOTAL reference.")

    # Independent high-precision decimal route, rather than calling rate() or
    # display_one_decimal() to manufacture expected benchmark results.
    with localcontext() as context:
        context.prec = 65
        rates = {key: Decimal(100) * values[3] / values[1] for key, values in REFERENCE.items()}
        one = Decimal("0.1")
        audits = {(r["period"], r["adjustment"]): r for r in report["row_audits"]}
        residuals = []
        for key, values in REFERENCE.items():
            audit = audits[key]
            require(str(rates[key].quantize(one, rounding=ROUND_HALF_UP)) == values[-1], "reference display")
            require(audit["ratio_display_percent"] == values[-1] and audit["display_matches"], "benchmark display")
            fraction = Fraction(audit["ratio_percent_exact"])
            near(audit["ratio_percent_approx"], rates[key])
            require(fraction.numerator * values[1] == fraction.denominator * 100 * values[3], "exact ratio cross product")
            p, labor, employed, unemployed, outside, _ = values
            for field, reference in (("labor_force_identity_residual_thousands", labor-employed-unemployed),
                                     ("population_identity_residual_thousands", p-labor-outside)):
                require(audit[field] == reference and abs(reference) <= 1, "identity residual")
                if reference:
                    residuals.append((key, field, reference))
            low = Decimal(100) * (Decimal(unemployed)-Decimal("0.5")) / (Decimal(labor)+Decimal("0.5"))
            high = Decimal(100) * (Decimal(unemployed)+Decimal("0.5")) / (Decimal(labor)-Decimal("0.5"))
            near(audit["level_rounding_envelope_percent"][0], low)
            near(audit["level_rounding_envelope_percent"][1], high)
            # Enumerate a 3x3 bounded perturbation grid and check the envelope.
            for du in (Decimal("-0.5"), Decimal(0), Decimal("0.5")):
                for dl in (Decimal("-0.5"), Decimal(0), Decimal("0.5")):
                    candidate = Decimal(100) * (unemployed+du) / (labor+dl)
                    require(low <= candidate <= high, "rounding envelope")
        require(len(residuals) == 2 and all(item[2] == -1 for item in residuals), "two residuals only")
        for item in report["comparison_grid"]:
            adj, earlier = item["adjustment"], item["earlier_period"]
            delta = rates[("2024-07", adj)] - rates[(earlier, adj)]
            displays = Decimal(REFERENCE[("2024-07", adj)][-1]) - Decimal(REFERENCE[(earlier, adj)][-1])
            near(item["ratio_difference_pp_approx"], delta)
            exact = Fraction(100 * REFERENCE[("2024-07", adj)][3], REFERENCE[("2024-07", adj)][1]) - Fraction(100 * REFERENCE[(earlier, adj)][3], REFERENCE[(earlier, adj)][1])
            require(Fraction(item["ratio_difference_pp_exact"]) == exact, "difference exact")
            require(item["round_after_subtraction_pp"] == str(delta.quantize(one, rounding=ROUND_HALF_UP)), "round after")
            require(item["subtract_published_rates_pp"] == str(displays.quantize(one)), "subtract displays")
            require(item["unemployed_level_change_thousands"] == REFERENCE[("2024-07", adj)][3] - REFERENCE[(earlier, adj)][3], "count difference")
        require(report["primary_replication"]["all_match"] and report["all_six_rate_displays_match"] and report["identities_compatible_with_component_rounding"], "baseline success")
        july = rates[("2024-07", "SA")]
        annual = july-rates[("2023-07", "SA")]
        display_error_difference = (Decimal("4.3")-july) - (Decimal("3.5")-rates[("2023-07", "SA")])
        require(abs(annual + display_error_difference - Decimal("0.8")) < Decimal("1e-60"), "exercise rounding identity")
        near(report["diagnostics"]["july_sa_unemployed_over_population_percent"], Decimal(716300)/268644)
        near(report["diagnostics"]["july_sa_unemployed_over_employed_percent"], Decimal(716300)/161266)
        near(float(100 * (Decimal("4.3")/Decimal("4.1")-1)), 4.878048780487805)
        require(report["diagnostics"]["july_sa_unemployed_millions_display"] == "7.2", "millions")
    checks.append("Independent 65-digit decimal calculations, exact cross products, all four comparison cells, 54 rounding-envelope grid points and all worked/exercise determinate quantities agree.")

    for numerator in range(-200, 201):
        for denominator in (1, 2, 4, 10, 20, 40, 97):
            value = Fraction(numerator, denominator)
            reference = (Decimal(numerator)/denominator).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP)
            expected = "0.0" if reference == 0 else str(reference)
            require(module.display_one_decimal(value) == expected, "display including signed ties/zero")
    small = {"unemployed_thousands": 0, "labor_force_thousands": 1}
    require(module.rounding_envelope(small) == (0, 100), "nonnegative boundary envelope")
    full = {"unemployed_thousands": 1, "labor_force_thousands": 1}
    require(module.rounding_envelope(full) == (Fraction(100, 3), 100), "100 percent clipping")
    # Derive allowed integer residuals by explicit half-grid rounding errors.
    residual_values = {a-b-c for a in (Fraction(-1,2), 0, Fraction(1,2)) for b in (Fraction(-1,2), 0, Fraction(1,2)) for c in (Fraction(-1,2), 0, Fraction(1,2))}
    require(max(abs(x) for x in residual_values if x.denominator == 1) == 1, "integer residual bound")
    corrupted = deepcopy(data)
    bad_row = next(r for r in corrupted["rows"] if (r["period"], r["adjustment"]) == ("2024-06", "SA"))
    bad_row["labor_force_thousands"] = 168109
    bad_report = module.calculate(corrupted)
    require(bad_report["primary_replication"]["all_match"] and bad_report["all_six_rate_displays_match"], "corruption still fools rounded headlines")
    require(not bad_report["identities_compatible_with_component_rounding"], "identity detects corruption")
    require(bad_report["discrepancy_log"][2]["status"] == "unresolved-identity-residual", "dynamic discrepancy log")
    june_audit = next(r for r in bad_report["row_audits"] if (r["period"], r["adjustment"]) == ("2024-06", "SA"))
    require(june_audit["labor_force_identity_residual_thousands"] == 99, "exercise invented residual")
    near(june_audit["ratio_percent_approx"], 4.051537990232528)
    checks.append("2,807 signed rounding cases, zero/full-rate bounds, component-error enumeration and invented 100-thousand denominator error show the intended audit behavior.")

    invalid = []
    for field, value in (("labor_force_thousands",0), ("unemployed_thousands",-1),
                         ("unemployed_thousands",True), ("population_thousands",267002.0),
                         ("labor_force_thousands",1000001), ("period","2024-08"),
                         ("adjustment","sa"), ("published_rate_percent",3.8),
                         ("published_rate_percent","3.80"), ("published_rate_percent","100.1"),
                         ("published_rate_percent","NaN"), ("employed_thousands",200000)):
        changed = deepcopy(data)
        changed["rows"][0][field] = value
        invalid.append(changed)
    for key, value in (("schema_version",True), ("source_release","2026-10-07"), ("level_unit","persons")):
        changed = deepcopy(data)
        changed[key] = value
        invalid.append(changed)
    changed = deepcopy(data)
    changed["rows"][1] = deepcopy(changed["rows"][0])
    invalid.append(changed)
    changed = deepcopy(data)
    changed["rows"].pop()
    invalid.append(changed)
    changed = deepcopy(data)
    changed["rows"][0]["extra"] = 0
    invalid.append(changed)
    for changed in invalid:
        rejected(lambda changed=changed: module.validate_data(changed))
    for raw in (b'{"x":1,"x":2}', b'{"x":NaN}', b'{"x":Infinity}', b'[]'):
        if raw != b'[]':
            rejected(lambda raw=raw: module.decode_json(raw))
    checks.append("18 invalid type/schema/key/unit/denominator cases rejected, plus duplicate JSON fields and nonfinite constants.")

    original_bytes = {name: (PROJECTS/name).read_bytes() for name in (DATA, EXTRACT, MANIFEST)}
    def invoke(directory, optimized=False, extra=()):
        return subprocess.run([sys.executable]+(["-O"] if optimized else [])+[str(SCRIPT),str(directory)]+list(extra),
                              cwd=directory, capture_output=True, text=True, check=False)
    with tempfile.TemporaryDirectory(prefix="v04-c12-check-") as directory:
        temp = Path(directory)
        def reset():
            for name, raw in original_bytes.items():
                (temp/name).write_bytes(raw)
        def rehash():
            updated = json.loads((temp/MANIFEST).read_text())
            updated["sha256"] = {name:hashlib.sha256((temp/name).read_bytes()).hexdigest() for name in (DATA,EXTRACT)}
            (temp/MANIFEST).write_text(json.dumps(updated))
        reset()
        for optimized in (False,True):
            process = invoke(temp,optimized)
            require(process.returncode == 0 and not process.stderr, "offline CLI baseline")
            output = json.loads(process.stdout)
            require(output["primary_replication"] == report["primary_replication"], "CLI agrees")
            # Each invalid data case gets fresh local hashes so validation,
            # rather than a superficial file hash failure, must catch it.
            for changed in invalid:
                reset()
                (temp/DATA).write_text(json.dumps(changed))
                rehash()
                process = invoke(temp,optimized)
                require(process.returncode == 1 and not process.stdout and "Cannot reproduce frozen case:" in process.stderr, "CLI explicit validation")
            reset()
        (temp/DATA).write_bytes(original_bytes[DATA]+b"\n")
        process = invoke(temp)
        require(process.returncode == 1 and "hash mismatch" in process.stderr, "whitespace integrity mutation")
        reset()
        (temp/DATA).write_text(json.dumps(corrupted))
        rehash()
        process = invoke(temp)
        require(process.returncode == 1 and "differ from" in process.stderr, "copies disagree")
        # Both copies deliberately changed in a temporary directory only.
        (temp/EXTRACT).write_text((temp/EXTRACT).read_text().replace("2024-06|SA|268438|168009|", "2024-06|SA|268438|168109|"))
        rehash()
        process = invoke(temp)
        require(process.returncode == 3 and not process.stderr and not json.loads(process.stdout)["identities_compatible_with_component_rounding"], "numerical failure exit")
        reset()
        changed_manifest = json.loads(original_bytes[MANIFEST])
        changed_manifest["schema_version"] = True
        (temp/MANIFEST).write_text(json.dumps(changed_manifest))
        rejected(lambda: module.load_inputs(temp))
        reset()
        require(invoke(temp,extra=("unexpected",)).returncode == 2, "usage error")
        (temp/MANIFEST).unlink()
        require(invoke(temp).returncode == 1, "missing file")
        default = subprocess.run([sys.executable,str(SCRIPT)],cwd=temp,capture_output=True,text=True,check=False)
        require(default.returncode == 0 and not default.stderr, "default path independent of cwd")
    require(all((PROJECTS/name).read_bytes() == raw for name,raw in original_bytes.items()), "inputs unchanged")
    preserved = json.loads((PROJECTS/"v04-c12-benchmark.json").read_text())
    metadata = preserved.pop("reproducibility")
    require(preserved == report and metadata["input_sha256"] == manifest["sha256"] and metadata["network_required"] is False, "preserved benchmark")
    checks.append("Normal and -O CLI reject all 18 invalid cases; byte/hash drift, cross-copy disagreement, numerical failure exit3, manifest type, missing file, usage and unrelated-directory behavior checked without input mutation.")

    html = (BOOK/"content/chapters/v04-c12.html").read_text()
    parser = ChapterParser()
    parser.feed(html)
    require(parser.worked >= 2 and parser.exercises == parser.solutions == 8, "chapter exercise/worked structure")
    sources = json.loads((BOOK/"content/reviews/v04-c12-sources.json").read_text())
    require(parser.sources == {r["id"] for r in sources}, "source records")
    for source in sources:
        require(set(source) == {"id","title","url","use","checked","verification"} and source["id"].startswith("v04-c12-"), "source record contract")
    downloads = [href for href in parser.links if href.startswith("v04-c12-")]
    require(len(downloads) == 6 and all("/" not in name and (PROJECTS/name).is_file() for name in downloads), "flat project downloads")
    require("v04-c11.html" in parser.links and "curriculum.html#v04" in parser.links, "predecessor and planned volume package")
    for term in ("Teach-back", "Delayed check", "percentage point", "manual transcription", "not synthetic", "sampling"):
        require(term in html, "instructional scope: "+term)
    checks.append("Two worked examples, eight matching exercise/solution items, six real flat downloads, scoped sources, predecessor/planned-successor and retention structure checked.")
    return {"status":"passed", "checks":checks, "limitations":[
        "Arithmetic validates the frozen published-aggregate reconstruction; it does not independently rebuild BLS weighting, seasonal adjustment, survey error or causal effects.",
        "Official values were inspected and manually transcribed; the independent local reference is still a human-readable transcription, not an original-source-byte archive or source-authenticity proof.",
        "Exact computations and local structural tests do not replace root editorial review, external human expert review, or pending visual/mobile/print QA.",
    ]}


if __name__ == "__main__":
    print(json.dumps(check(),indent=2))
